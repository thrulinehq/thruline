//! BUILD-SPEC §4.3 — the Gemini CLI adapter.
//!
//! # The contract was checked, not assumed
//!
//! §4.3 says *"verify event names and stdin/stdout JSON contract in the Gemini
//! CLI hooks docs"*, and that instruction is why the Claude Code adapter is
//! correct: checking found that `PostToolUse` fires **only on success**, without
//! which this product would have been blind to every failing test run. The same
//! check was run here against `docs/hooks/reference.md` (retrieved 2026-09-02).
//! §4.3's `BeforeTool` / `AfterTool` and `.gemini/settings.json` are confirmed.
//! Six things it does not say are recorded below, and three of them change what
//! this adapter can promise.
//!
//! ## [CONFLICT-6] There is no `Stop` and no `PostCompress`
//!
//! The stop analogue is `AfterAgent` — *"fires once per turn after the model
//! generates its final response"* — carrying `prompt`, `prompt_response` and
//! `stop_hook_active`. Compaction is `PreCompress` **only**, and it is
//! *"Advisory Only. Fired asynchronously. It cannot block or modify the
//! compression process."*
//!
//! **Capability gap, recorded rather than papered over:** on Gemini, §10's
//! compaction-loss report has a `compaction_pre` and no `compaction_post`. The
//! post side would have to be inferred from later behaviour, and this adapter
//! does not infer it. A session with a compaction boundary and no post marker
//! is a session whose compaction ThruLine saw the start of.
//!
//! ## [CONFLICT-9, new] `AfterTool` is *not* success-only, and the failure is a
//! field rather than an event
//!
//! Claude Code needs `PostToolUse` **and** `PostToolUseFailure` because its doc
//! says `PostToolUse` *"runs immediately after a tool completes successfully"*.
//! Gemini's doc places no such restriction on `AfterTool` and gives
//! `tool_response` an **optional `error`** — so the failure arrives on the same
//! event, in a field. There is therefore no second event to subscribe to, and
//! `ok` is derived from `tool_response.error`.
//!
//! This is the single most important line in this file. Getting it backwards in
//! either direction is a systematic bias: subscribing to a non-existent failure
//! event captures nothing extra and looks fine, while reading every `AfterTool`
//! as a success reproduces exactly the Claude Code blindness the check caught.
//!
//! ## [CONFLICT-10, new] `SessionEnd` is best-effort, more strongly than
//! Claude Code's 1.5 s budget
//!
//! Verbatim: *"The CLI **will not wait** for this hook to complete and ignores
//! all flow-control fields."* So a `SessionEnd` hook can be killed mid-write.
//! Nothing may depend on it having run: this adapter writes one line with one
//! append and treats its absence as ordinary.
//!
//! ## Three smaller ones
//!
//! - **Timeout is milliseconds** (default 60000) — a different unit from both
//!   other harnesses, and the easiest possible bug in the settings writer.
//! - **`Notification`** with `notification_type: "ToolPermission"` is Gemini's
//!   permission signal — §10's "permission denied" stop reason. It is
//!   *"Observability Only"*, so it can be recorded and can never be acted on.
//! - **There is no `tool_use_id`.** `BeforeTool` and `AfterTool` cannot be
//!   correlated by id the way Claude Code's can. Order and `tool_name` are all
//!   there is, and that is a real limit on attribution rather than a detail.
//!
//! ## `AfterModel` is deliberately not subscribed
//!
//! It fires *"for **every chunk** generated by the model."* A command hook on
//! it would run hundreds of times per turn. Not subscribing is a decision, so
//! it is written here rather than left looking like an omission.
//!
//! # "Silence is Mandatory"
//!
//! Verbatim from the doc, and stricter than Claude Code's contract: *"Your
//! script must not print any plain text to `stdout` other than the final
//! JSON."* This adapter prints nothing at all, on every path.

use serde_json::Value;

/// The hook events this adapter subscribes to.
///
/// Verified against the vendor documentation (retrieved 2026-09-02). No
/// `Stop`, no `PostCompress`, no `AfterModel` — see the module docs for why
/// each absence is a decision.
pub const SUBSCRIBED_EVENTS: &[&str] = &[
    "SessionStart",
    "BeforeAgent",
    "BeforeTool",
    "AfterTool",
    "AfterAgent",
    "PreCompress",
    "Notification",
    "SessionEnd",
];

/// The hook timeout this adapter writes into `.gemini/settings.json`.
///
/// **Milliseconds.** Gemini is the only one of the three harnesses that does
/// not use seconds, and a `5` here would be a five-millisecond budget that
/// killed every delivery.
pub const TIMEOUT_MS: u64 = 5_000;

/// Map a Gemini hook event name onto a §3.1 event kind.
pub fn event_kind_for(hook_event: &str) -> Option<&'static str> {
    Some(match hook_event {
        "SessionStart" => "session_start",
        "BeforeAgent" => "user_prompt",
        "BeforeTool" => "tool_call",
        "AfterTool" => "tool_result",
        // The stop analogue. There is no `Stop` event on this harness.
        "AfterAgent" => "stop",
        // And no `compaction_post` counterpart — see the module docs.
        "PreCompress" => "compaction_pre",
        "Notification" => "note",
        "SessionEnd" => "session_end",
        _ => return None,
    })
}

/// Did the tool this `AfterTool` describes succeed?
///
/// `Ok(true)` / `Ok(false)` when the envelope is the documented shape; `Err`
/// when it is not. **Not a `bool` with a default**: an envelope this adapter
/// has not seen is refused rather than coerced, because the only value a
/// coercion could pick is `true`, and "the record did not say" would then be
/// indistinguishable from "the tool succeeded". That is the failure the Claude
/// Code check caught, arriving through a different door.
pub fn tool_ok(payload: &Value) -> Result<bool, EnvelopeRefusal> {
    let response = payload
        .get("tool_response")
        .ok_or(EnvelopeRefusal::MissingToolResponse)?;
    let object = response
        .as_object()
        .ok_or(EnvelopeRefusal::ToolResponseNotAnObject)?;
    match object.get("error") {
        None | Some(Value::Null) => Ok(true),
        Some(_) => Ok(false),
    }
}

/// Why an envelope was refused rather than read.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum EnvelopeRefusal {
    /// `AfterTool` with no `tool_response`. The documented shape always has
    /// one; a delivery without it is a version this adapter has not seen.
    MissingToolResponse,
    /// `tool_response` present but not an object — e.g. a bare string. Reading
    /// "no `error` key" off a string would report success for a shape nobody
    /// has verified.
    ToolResponseNotAnObject,
}

impl EnvelopeRefusal {
    pub fn as_str(self) -> &'static str {
        match self {
            EnvelopeRefusal::MissingToolResponse => "after_tool_without_tool_response",
            EnvelopeRefusal::ToolResponseNotAnObject => "after_tool_response_not_an_object",
        }
    }
}

/// The final assistant message, from the one event that carries it.
///
/// `AfterAgent.prompt_response`, not the transcript: the transcript is a hint
/// (§0.2) and this is the harness's own statement of what it said.
pub fn final_message(payload: &Value) -> Option<&str> {
    payload.get("prompt_response").and_then(Value::as_str)
}

