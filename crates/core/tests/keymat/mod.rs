//! A209-C11 — shared key-material controls.
//!
//! Round 11 found two regressions that eleven rounds of green suites had
//! not: a final payload line shipped, and a narrow wrap shipped whole.
//! Both were invisible for the same reason — every control sampled the
//! FIRST payload line, or the first three, and asserted only that one
//! fragment was gone. A rule with two implementations (detection and span
//! extension) needs a control that looks at the whole body, because the
//! two disagree precisely at its END.
//!
//! So the assertion here is total: **no 24-character window of the key
//! body may survive anywhere in the output**, for every one of the 1,601
//! windows. A tail, a final wrap, a middle line, or a re-wrapped fragment
//! all fail it identically.

