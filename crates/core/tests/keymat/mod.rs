/// Length of the fragment window. Short enough that a single surviving
/// final wrap (16 characters plus its neighbours) cannot slip through a
/// line-granular check, long enough that a collision in masked output is
/// not a physical possibility.
pub const FRAG: usize = 24;

/// The concatenated base64 payload, banners removed.
pub fn body() -> String {
    let lines: Vec<&str> = REAL_RSA_KEY.lines().collect();
    lines[1..lines.len() - 1].concat()
}

/// The key re-wrapped at an arbitrary column. Real tools emit 64 (RFC
/// 7468), 70 (OpenSSH) and 76 (MIME); a log pipeline, an editor, or a
/// terminal capture can produce any width at all, which is the second
/// generator round 11 named.
pub fn rewrap(w: usize) -> String {
    let b = body();
    let mut out = String::from("-----BEGIN PRIVATE KEY-----\n");
    let bytes = b.as_bytes();
    let mut i = 0;
    while i < bytes.len() {
        let end = (i + w).min(bytes.len());
        out.push_str(&b[i..end]);
        out.push('\n');
        i = end;
    }
    out.push_str("-----END PRIVATE KEY-----");
    out
}

/// Apply a per-line decoration to every line of a document.
pub fn decorate(doc: &str, prefix: &str) -> String {
    doc.lines()
        .map(|l| format!("{prefix}{l}"))
        .collect::<Vec<_>>()
        .join("\n")
}

/// Hard-wrap every line at `cols`, the way a fixed-width log pane, an
/// 80-column terminal capture, or `fold -w` does. This is what breaks the
/// equal-width assumption: a decorated 64-wrapped body hard-wrapped at 80
/// alternates run lengths instead of repeating one.
pub fn hard_wrap(doc: &str, cols: usize) -> String {
    let mut out: Vec<String> = Vec::new();
    for l in doc.lines() {
        if l.is_empty() {
            out.push(String::new());
            continue;
        }
        let b = l.as_bytes();
        let mut i = 0;
        while i < b.len() {
            let end = (i + cols).min(b.len());
            out.push(l[i..end].to_string());
            i = end;
        }
    }
    out.join("\n")
}

/// The first 24-character window of the key body that survives in `out`,
/// if any. Scans EVERY window — this is the assertion that eleven rounds
/// of first-line sampling did not make.
pub fn surviving_fragment(out: &str) -> Option<String> {
    let b = body();
    if b.len() < FRAG {
        return None;
    }
    for i in 0..=(b.len() - FRAG) {
        let w = &b[i..i + FRAG];
        if out.contains(w) {
            return Some(format!("body[{i}..{}] = {w}", i + FRAG));
        }
    }
    None
}

/// Why `doc` leaks, if it does: either the detector never fired, or a
/// fragment of the body survived masking.
pub fn leak_reason(doc: &str) -> Option<String> {
    let (out, rec) = mask_recorded(doc);
    if !rec.families.contains("private_key_block") {
        return Some("private_key_block never fired".to_string());
    }
    surviving_fragment(&out).map(|f| format!("survived: {f}"))
}

