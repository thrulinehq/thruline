//! Embeds the built UI into the binary.
//!
//! `thruline ui` has to work from any directory on any machine, with no npm, no
//! dev server, and no source tree. That means the 236 KB allowlisted `ui/dist`
//! travels inside the executable rather than beside it.
//!
//! `ui/dist` is COMMITTED for exactly this reason (it was gitignored until
//! RA1). It is safe to commit and the safety is structural, not a promise:
//! `ui/vite.config.js` switches `publicDir` off for `vite build` and copies only
//! an allowlist (`fonts/`), so a production build carries no `fixtures/` and
//! therefore no transcript content. Project data is served at runtime from
//! `~/.thruline/export`, never from the binary.
//!
//! No dependency is added for this. A generated table of `include_bytes!` is the
//! least machinery that meets the requirement (Rule 2), and it keeps the
//! embedded set auditable: the generated file names every path that shipped.
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let dist = manifest
        .join("../../ui/dist")
        .canonicalize()
        .unwrap_or_else(|e| {
            panic!(
                "crates/cli/build.rs: cannot read the built UI at ui/dist ({e}).\n\
                 ui/dist is committed to this repository and embedded into the binary by \
                 `thruline ui`.\n\
                 Restore it (`git checkout -- ui/dist`) or rebuild it (`cd ui && npm run build`). \
                 Refusing to build a `thruline ui` with no UI in it."
            )
        });

    let mut files = Vec::new();
    collect(&dist, &dist, &mut files);
    files.sort();
    if files.is_empty() {
        panic!("crates/cli/build.rs: ui/dist exists but is empty — nothing to embed.");
    }

    let mut out = String::from(
        "// @generated by crates/cli/build.rs — do not edit.\n\
         pub static UI_ASSETS: &[(&str, &str, &[u8])] = &[\n",
    );
    for rel in &files {
        let abs = dist.join(rel);
        println!("cargo:rerun-if-changed={}", abs.display());
        out.push_str(&format!(
            "    ({:?}, {:?}, include_bytes!({:?})),\n",
            rel.replace('\\', "/"),
            mime_for(rel),
            abs.display().to_string()
        ));
    }
    out.push_str("];\n");

    let dest = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("ui_assets.rs");
    fs::write(&dest, out).expect("writing the embedded-asset table");
    println!("cargo:rerun-if-changed={}", dist.display());
    println!("cargo:rerun-if-changed=build.rs");

    emit_code_digest(&manifest);
}

/// P2b — stamp the binary with a digest of the engine source it was built from.
///
/// `thruline perf` derives a figure's currency at read, and one of the axes is
/// "has the code beneath this measurement changed". A binary cannot answer that
/// from a commit sha: a sha identifies a tree, not the tree this executable was
/// actually compiled from, and it moves for a markdown edit that changes nothing
/// beneath a measurement. So the code axis is a digest over the source.
///
/// The algorithm is `thruline_core::perf_basis::code_digest` and the file set is
/// `perf_basis::engine_sources`. Both are duplicated here because a build script
/// cannot depend on the crate it is building without compiling the whole engine
/// for the host. `crates/cli/tests/a192_code_digest.rs` pins the two copies
/// together by walking the tree with the core implementation and asserting the
/// embedded value matches — so this copy is verified on every test run rather
/// than trusted.
///
/// A tree this cannot read yields `unavailable`, never a guess. An unavailable
/// digest matches no basis, so every figure renders "stale basis — re-measure",
/// which is the correct answer when the code under measurement cannot be
/// identified.
fn emit_code_digest(manifest: &Path) {
    let root = manifest.join("../..");
    let Ok(root) = root.canonicalize() else {
        println!("cargo:rustc-env=THRULINE_CODE_DIGEST=unavailable");
        return;
    };
    let mut entries: Vec<(String, Vec<u8>)> = Vec::new();
    let mut ok = true;
    for fixed in [
        "Cargo.toml",
        "Cargo.lock",
        "rust-toolchain.toml",
        "crates/core/Cargo.toml",
        "crates/cli/Cargo.toml",
        "crates/cli/build.rs",
    ] {
        let path = root.join(fixed);
        match fs::read(&path) {
            Ok(bytes) => {
                println!("cargo:rerun-if-changed={}", path.display());
                entries.push((fixed.to_string(), bytes));
            }
            Err(_) => ok = false,
        }
    }
    for dir in ["crates/core/src", "crates/cli/src"] {
        let dir = root.join(dir);
        println!("cargo:rerun-if-changed={}", dir.display());
        ok &= collect_rs(&root, &dir, &mut entries);
    }
    if !ok {
        println!("cargo:rustc-env=THRULINE_CODE_DIGEST=unavailable");
        return;
    }
    println!(
        "cargo:rustc-env=THRULINE_CODE_DIGEST={}",
        code_digest(&mut entries)
    );
}

fn collect_rs(root: &Path, dir: &Path, out: &mut Vec<(String, Vec<u8>)>) -> bool {
    let Ok(entries) = fs::read_dir(dir) else {
        return false;
    };
    let mut ok = true;
    for entry in entries {
        let Ok(entry) = entry else {
            return false;
        };
        let path = entry.path();
        if path.is_dir() {
            ok &= collect_rs(root, &path, out);
        } else if path.extension().is_some_and(|e| e == "rs") {
            let rel = path
                .strip_prefix(root)
                .unwrap_or(path.as_path())
                .to_string_lossy()
                .replace('\\', "/");
            println!("cargo:rerun-if-changed={}", path.display());
            match fs::read(&path) {
                Ok(bytes) => out.push((rel, bytes)),
                Err(_) => ok = false,
            }
        }
    }
    ok
}

/// Byte-for-byte the algorithm in `thruline_core::perf_basis::code_digest`.
fn code_digest(entries: &mut [(String, Vec<u8>)]) -> String {
    use sha2::{Digest, Sha256};

    entries.sort_by(|a, b| a.0.cmp(&b.0));
    let hex = |bytes: &[u8]| -> String { bytes.iter().map(|b| format!("{b:02x}")).collect() };
    let mut outer = Sha256::new();
    outer.update(b"thruline-code-digest-v1\n");
    for (path, bytes) in entries.iter() {
        let mut inner = Sha256::new();
        inner.update(bytes);
        outer.update(path.as_bytes());
        outer.update(b"\n");
        outer.update(hex(&inner.finalize()).as_bytes());
        outer.update(b"\n");
    }
    format!("sha256:{}", &hex(&outer.finalize())[..16])
}

fn collect(root: &Path, dir: &Path, out: &mut Vec<String>) {
    let entries = fs::read_dir(dir).unwrap_or_else(|e| panic!("reading {}: {e}", dir.display()));
    for entry in entries {
        let entry = entry.expect("directory entry");
        let path = entry.path();
        let name = entry.file_name();
        let name = name.to_string_lossy();
        if name.starts_with('.') {
            continue;
        }
        if path.is_dir() {
            collect(root, &path, out);
        } else {
            let rel = path
                .strip_prefix(root)
                .expect("dist child")
                .to_string_lossy()
                .into_owned();
            out.push(rel);
        }
    }
}

fn mime_for(rel: &str) -> &'static str {
    match rel.rsplit('.').next().unwrap_or("") {
        "html" => "text/html; charset=utf-8",
        "js" | "mjs" => "text/javascript; charset=utf-8",
        "css" => "text/css; charset=utf-8",
        "json" => "application/json; charset=utf-8",
        "svg" => "image/svg+xml",
        "woff2" => "font/woff2",
        "woff" => "font/woff",
        "png" => "image/png",
        "jpg" | "jpeg" => "image/jpeg",
        "ico" => "image/x-icon",
        "md" | "txt" => "text/plain; charset=utf-8",
        _ => "application/octet-stream",
    }
}
