#!/usr/bin/env node
// Prints every string in HQ_COPY as prose, grouped by section, placeholders
// shown in braces — the review copy for docs/HQ-COPY.md.
//
//   node ui/src/workspace/hq-copy-export.mjs > docs/HQ-COPY.md
//
// hq-copy.test.js asserts the file on disk equals this output, so a wording
// change without a regenerate fails the suite.

import { fileURLToPath } from 'node:url'
import { HQ_COPY } from './hq-copy.js'

const REGISTER_LABEL = { manager: 'Plain', operator: 'Technical' }
const TRIPLET_LABEL = { said: 'Said', record: 'Record', do: 'Do', prompt: 'Prompt for the agent' }

function flatten(obj, prefix = '', out = []) {
  for (const [k, v] of Object.entries(obj)) {
    const key = prefix ? `${prefix}.${k}` : k
    if (v && typeof v === 'object' && !Array.isArray(v)) flatten(v, key, out)
    else out.push([key, v])
  }
  return out
}

export function renderCopyMarkdown(copy = HQ_COPY) {
  const L = []
  const p = (s = '') => L.push(s)

  p('# HQ Verdict Panel — the copy')
  p()
  p('Every user-visible string of the Verdict tab, generated from `ui/src/workspace/hq-copy.js`.')
  p('Do not edit this file by hand: edit the copy file, then regenerate with')
  p('`node ui/src/workspace/hq-copy-export.mjs > docs/HQ-COPY.md` and update the golden with')
  p('`UPDATE_GOLDEN=1 node --test ui/src/workspace/hq-copy.test.js`. Placeholders are shown in braces.')
  p()
  p('Plain is the manager register (default; full sentences, no file paths). Technical is the operator')
  p('register (terse; paths and receipt ids inline). The record is the subject of every negative sentence.')
  p()

  // R8-VOCABULARY (ruling R-2026-09-23-8; design record §5 supersedes the
  // Verdict Panel brief's words). The switch was decided per PRODUCING STATE —
  // which engine state yields the word — not per word, and a real state with
  // no §5 equivalent keeps its name rather than being forced into one.
  p('## The state-word switch (R8-VOCABULARY, ruling R-2026-09-23-8)')
  p()
  p('Design record §5 words: Proven · Not proven · In progress · Recorded · Needs a re-check')
  p('(plus Approved / Ready for approval on the decision). Decided per producing state:')
  p()
  p('| Producing state (engine) | Was | Now | Why |')
  p('|---|---|---|---|')
  p('| claim `supported`; ask `proven` | Proven | **Proven** | §5 has the same word. |')
  p('| claim `unsupported`; ask `claimed_only` | Not proven | **Not proven** | §5 has the same word. |')
  p('| claim/ask `unverifiable`, capture NOT degraded | Couldn\'t check | **Recorded** | A reading exists and settles nothing — §5\'s `recorded` exactly. |')
  p('| `insufficient_evidence` | Couldn\'t check | **Recorded** | Evidence is here; it does not decide. |')
  p('| `not_evaluated` | Couldn\'t check | **Recorded** | Read and set aside; still never its own state word — the Record line says why. |')
  p('| external adapter report, state not `failed` | Couldn\'t check | **Recorded** | A report exists and qualifies nothing. |')
  p('| acceptance criterion neither `verified` nor `failed` | Couldn\'t check | **Recorded** | The contract was evaluated; this line settled nothing. |')
  p('| attestation ground `integrity_incomplete`, `capture_degraded` | Couldn\'t check | **Fog** | A recording gap, not a reading — the same rule the panel already used. |')
  p('| promise `open`/`dropped`; ask `partial`/`scope_shrunk`/`untouched`/`dropped`/`refused`; stop `user_interrupt`/`error`/`permission_denied`/`context_limit` | Loose thread | **Loose thread — KEPT** | §5 has no word for a promise made and abandoned. "In progress" would assert work is underway when the record shows it stopped. |')
  p('| claim/ask `unverifiable` when capture IS degraded; `chain_intact_false`; `raw_files_missing` | Fog | **Fog — KEPT** | §5 has no word for "nothing was reliably recorded". "Recorded" would assert a reading exists; "Needs a re-check" would assert something was checked. |')
  p('| criterion with no link row (Change model only) | — | In progress | Already §5; unchanged by this switch. |')
  p('| criterion whose evidence no longer applies (Change model only) | — | Needs a re-check | Already §5; unchanged by this switch. |')
  p()
  p('Engine slugs are unchanged (`couldnt`, `couldnt_check`, `WORDKEY.couldnt = couldnt-check`):')
  p('they are keys and query tokens, never displayed, and saved views keep working.')
  p('No state changed meaning, and no verdict path was touched.')
  p()

  p('## States')
  p()
  for (const [key, s] of Object.entries(copy.states)) p(`- **${s.word}** — ${s.subtitle} (\`${key}\`)`)
  p()

  p('## Vocabulary — engine word → panel word')
  p()
  p('| Engine says | Panel says | Note |')
  p('|---|---|---|')
  for (const [engine, v] of Object.entries(copy.vocabulary)) {
    const panel = v.dropped ? '*(dropped — never rendered)*' : v.panel
    const notes = []
    if (v.chip) notes.push(`chip: ${v.chip}`)
    if (v.record_line) notes.push(`Record line: "${v.record_line}"`)
    if (v.subtitle) notes.push(`subtitle: ${v.subtitle}`)
    if (v.rule) notes.push(v.rule)
    p(`| ${engine.replace(/_/g, ' ')} | ${panel} | ${notes.join('; ')} |`)
  }
  p()

  p('## Finding kinds')
  p()
  for (const [key, label] of Object.entries(copy.kinds)) p(`- **${label}** (\`${key}\`)`)
  p()

  p('## Detectors — engine id → Plain phrase')
  p()
  p('Plain never shows a detector id; Technical shows it in a code chip. An id with no entry renders with its underscores replaced.')
  p()
  for (const [id, phrase] of Object.entries(copy.detectors)) p(`- \`${id}\` → ${phrase}`)
  p()

  p('## Session headline')
  p()
  for (const [key, regs] of Object.entries(copy.headline)) {
    p(`### ${key}`)
    p()
    for (const [reg, text] of Object.entries(regs)) p(`- ${REGISTER_LABEL[reg]}: ${text}`)
    p()
  }

  p('## Said / Record / Do families')
  p()
  for (const [key, regs] of Object.entries(copy.families)) {
    p(`### ${key}`)
    p()
    for (const [reg, triplet] of Object.entries(regs)) {
      p(`**${REGISTER_LABEL[reg]}**`)
      p()
      for (const [part, text] of Object.entries(triplet)) p(`- ${TRIPLET_LABEL[part]}: ${text}`)
      p()
    }
  }

  p('## You clicked in the trace')
  p()
  p(`Link under every card: ${copy.clicked.link}`)
  p()
  for (const [type, card] of Object.entries(copy.clicked)) {
    if (type === 'link') continue
    p(`### ${type}`)
    p()
    p(`- Title: ${card.title}`)
    p(`- Body: ${card.body}`)
    if (card.unquoted) p(`- Body when that one cannot be shown: ${card.unquoted}`)
    p()
  }

  p('## Checking sequence')
  p()
  p(`- Title: ${copy.phases.title}`)
  p(`- Sub line tree segment: ${copy.phases.sub_tree}`)
  p(`- Skip link: ${copy.phases.skip}`)
  p(`- Line label: ${copy.phases.checked_label}`)
  p()
  for (const [id, label] of Object.entries(copy.phases.labels)) p(`- \`${id}\` → ${label}`)
  p()
  p('Row counts, one noun per phase id:')
  p()
  for (const [key, text] of Object.entries(copy.phases.counts)) p(`- \`${key}\`: ${text}`)
  p()
  p(`- Elapsed counter: ${copy.phases.elapsed}`)
  p(`- When the log could not be fetched: ${copy.phases.failed}`)
  p(`- Its reason when the server answered with an error status: ${copy.phases.failed_http}`)
  p(`- Its reason when the answer was not a phase log: ${copy.phases.failed_body}`)
  p(`- Its reason when a step's measured time is missing from the log: ${copy.phases.failed_timing}`)
  p(`- The same failure on the landed verdict, in the "Checked:" line's place: ${copy.phases.failed_landed}`)
  p(`- In the "Checked:" line's place while the log is still loading: ${copy.phases.checked_loading}`)
  p(`- When some log lines could not be read: ${copy.phases.unparsed}`)
  p()
  p('The "Checked:" line after landing, one unit per count ("events" is allowed here; the brief bans it only as a headline count):')
  p()
  for (const [key, text] of Object.entries(copy.phases.checked)) p(`- \`${key}\`: ${text}`)
  p()

  p('## The four questions')
  p()
  p(`Heading: ${copy.questions.heading}`)
  p()
  for (const [key, q] of Object.entries(copy.questions)) {
    if (typeof q === 'string' && key !== 'heading') p(`- ${q} (\`${key}\`)`)
  }
  p()
  p('Answers, deterministic from the record:')
  p()
  for (const [key, text] of Object.entries(copy.questions.answers)) p(`- \`${key}\`: ${text}`)
  p()

  p('## Chrome — tabs, toggles, buttons, pills, footer')
  p()
  for (const [key, text] of flatten(copy.chrome)) p(`- \`${key}\`: ${text}`)
  p()

  p('## The Change workspace')
  p()
  p('The first user-facing surface of the delivery loop (T-2-4). One Change, one sentence, one named version;')
  p('six stages that are views; every disabled control carries both a reason and what would enable it.')
  p()
  for (const [key, text] of flatten(copy.change)) p(`- \`${key}\`: ${text}`)
  p()

  p('## Banned tokens')
  p()
  p('Never rendered, in any inflection: ' + copy.banned.map((t) => `\`${t}\``).join(', ') + '.')
  p()

  p('## Never on the Verdict tab')
  p()
  p('Engine words that must not reach the panel ("events" as a headline count; "reading" as the engine noun — the verb in `phases.labels.read_record` is allowed by name; the rest anywhere): ' +
    copy.forbidden_on_verdict.map((t) => `\`${t}\``).join(', ') + '.')
  p()

  return L.join('\n')
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  process.stdout.write(renderCopyMarkdown())
}
